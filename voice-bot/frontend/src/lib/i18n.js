export function isLanguage(code) {
    return LANGUAGES.some((l) => l.code === code);
}

export function htmlLang(code) {
    return LANGUAGES.find((l) => l.code === code)?.html ?? 'en';
}

/** Translates `key` for `lang`, falling back to English; `{name}` placeholders come from `vars`. */
export function t(lang, key, vars) {
    const table = STRINGS[lang] || en;
    const text = table[key] ?? en[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] === undefined ? '' : String(vars[name])));
}
